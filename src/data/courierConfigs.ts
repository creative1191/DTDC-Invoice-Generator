export const generateAwbNumber = (courier: CourierType): string => {
  if (courier === 'BLUEDART') {
    // Blue Dart standard 9 or 11-digit numeric waybills (starts with 82 or 71)
    return `82${Math.floor(10000000 + Math.random() * 90000000)}`;
  }
  if (courier === 'DELHIVERY') {
    // Delhivery standard 12-14 digit numeric waybills (starts with 14 or 32)
    return `14${Math.floor(1000000000 + Math.random() * 9000000000)}`;
  }
  // DTDC format (e.g. 7D134850071 or 7X...)
  const prefix = Math.random() > 0.3 ? '7D' : '7X';
  return `${prefix}${Math.floor(100000000 + Math.random() * 900000000)}`;
};

